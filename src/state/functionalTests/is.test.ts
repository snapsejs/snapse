import { describe, expect, it } from 'vitest'
import { compute, flush, peek, state, subscribe } from '@/index.js'

describe('is', () => {
  it('.is() on a computed state', () => {
    const s = state({ a: 1, b: 2 })
    const isThree = compute(() => s.a + s.b).is(3)
    const unsubscribe = subscribe(isThree)
    expect(peek(isThree)).toBe(true)
    s.a.set(2)
    flush()
    expect(peek(isThree)).toBe(false)
    s.b.set(1)
    flush()
    expect(peek(isThree)).toBe(true)
    s.a.set(0)
    flush()
    expect(peek(isThree)).toBe(false)
    unsubscribe()
  })

  it('.is() called many times on the same state: different and duplicate arguments', () => {
    const s = state(1)
    const is1a = s.is(1)
    const is1b = s.is(1)
    const is2 = s.is(2)
    const is3 = s.is(3)
    const unsubscribe = subscribe(compute(() => [peek(is1a), peek(is1b), peek(is2), peek(is3)]))
    expect(peek(is1a)).toBe(true)
    expect(peek(is1b)).toBe(true)
    expect(peek(is2)).toBe(false)
    expect(peek(is3)).toBe(false)
    s.set(2)
    flush()
    expect(peek(is1a)).toBe(false)
    expect(peek(is1b)).toBe(false)
    expect(peek(is2)).toBe(true)
    expect(peek(is3)).toBe(false)
    s.set(3)
    flush()
    expect(peek(is1a)).toBe(false)
    expect(peek(is1b)).toBe(false)
    expect(peek(is2)).toBe(false)
    expect(peek(is3)).toBe(true)
    s.set(1)
    flush()
    expect(peek(is1a)).toBe(true)
    expect(peek(is1b)).toBe(true)
    expect(peek(is2)).toBe(false)
    expect(peek(is3)).toBe(false)
    unsubscribe()
  })

  it('should not corrupt source state type when multiple .is() results are unsubscribed', () => {
    const s = state(1)
    const r1 = s.is(1)
    const r2 = s.is(2)
    const r3 = s.is(3)
    const u1 = subscribe(r1)
    const u2 = subscribe(r2)
    const u3 = subscribe(r3)
    u1()
    u2()
    u3()
    expect(() => peek(s)).not.toThrow()
    expect(peek(s)).toBe(1)
    expect(() => s.is(4)).not.toThrow()
  })

  it('should correctly evaluate the .is function', () => {
    const s = state({ a: 1, b: 'ko', c: 2 })
    const t = s.a.is(2)
    const u = s.c.is(2)
    const v = compute(() => [peek(t), peek(u)])
    const unsubscribe = subscribe(v)
    expect(peek(t)).toBe(false)
    expect(peek(u)).toBe(true)
    s.c.set(1)
    flush()
    expect(peek(t)).toBe(false)
    expect(peek(u)).toBe(false)
    s.a.set(2)
    flush()
    expect(peek(t)).toBe(true)
    expect(peek(u)).toBe(false)
    s.a.set(1)
    flush()
    expect(peek(t)).toBe(false)
    expect(peek(u)).toBe(false)
    unsubscribe()
  })

  it('should correctly evaluate the .is function on a state value', () => {
    const s = state({ a: 1, b: 'ko', c: 2, d: 1 })
    const t = s.a.is(s.d)
    const u = s.c.is(s.d)
    const v = compute(() => [peek(t), peek(u)])
    const unsubscribe = subscribe(v)
    expect(peek(t)).toBe(true)
    expect(peek(u)).toBe(false)
    s.c.set(1)
    flush()
    expect(peek(t)).toBe(true)
    expect(peek(u)).toBe(true)
    s.a.set(2)
    flush()
    expect(peek(t)).toBe(false)
    expect(peek(u)).toBe(true)
    s.d.set(2)
    flush()
    expect(peek(t)).toBe(true)
    expect(peek(u)).toBe(false)
    s.a.set(1)
    s.c.set(2)
    flush()
    expect(peek(t)).toBe(false)
    expect(peek(u)).toBe(true)
    unsubscribe()
  })

  it('should handle stateful compared values efficiently', () => {
    const s = state({
      reference: 1,
      compared: 2,
    })
    const d = s.reference.is(s.compared)
    const unsubscribe = subscribe(d)
    expect(peek(d)).toBe(false)
    s.compared.set(1)
    flush()
    expect(peek(d)).toBe(true)
    s.reference.set(3)
    flush()
    expect(peek(d)).toBe(false)
    s.compared.set(3)
    flush()
    expect(peek(d)).toBe(true)
    unsubscribe()
  })

  it('should handle many derived states whose stateful comparands share a value', () => {
    const s = state({ a: 1, b: 5, c: 5 })
    const x = s.a.is(s.b)
    const y = s.a.is(s.c)
    const ux = subscribe(x)
    const uy = subscribe(y)
    expect(peek(x)).toBe(false)
    expect(peek(y)).toBe(false)
    s.b.set(3)
    flush()
    expect(peek(x)).toBe(false)
    expect(peek(y)).toBe(false)
    s.a.set(3)
    flush()
    expect(peek(x)).toBe(true)
    expect(peek(y)).toBe(false)
    s.c.set(3)
    flush()
    expect(peek(y)).toBe(true)
    ux()
    uy()
  })

  it('should unsubscribe cleanly when comparing against a falsy value', () => {
    const s = state({ a: 1 })
    const d = s.a.is(0)
    const unsubscribe = subscribe(d)
    expect(peek(d)).toBe(false)
    s.a.set(0)
    flush()
    expect(peek(d)).toBe(true)
    unsubscribe()
    const d2 = s.a.is(0)
    const u2 = subscribe(d2)
    expect(peek(d2)).toBe(true)
    s.a.set(1)
    flush()
    expect(peek(d2)).toBe(false)
    u2()
  })

  it('should work to call .is with an already used value', () => {
    const s = state(3)
    const a = s.is(3)
    const b = s.is(3)
    const ua = subscribe(a)
    const ub = subscribe(b)
    s.set(5)
    const c = s.is(3)
    const uc = subscribe(c)
    flush()
    expect(peek(a)).toBe(false)
    expect(peek(b)).toBe(false)
    expect(peek(c)).toBe(false)
    ua()
    ub()
    uc()
  })

  it('correctly identifies and removes one of several .is() results sharing a compared value', () => {
    const s = state(1)
    const a = s.is(1)
    const b = s.is(1)
    const c = s.is(1)
    const ua = subscribe(a)
    const ub = subscribe(b)
    const uc = subscribe(c)
    expect(peek(a)).toBe(true)
    expect(peek(b)).toBe(true)
    expect(peek(c)).toBe(true)
    // Unsubscribe the middle entry specifically: a wrong (e.g. always-first) removal would
    //   corrupt tracking for `a` or `c` instead.
    ub()
    s.set(2)
    flush()
    expect(peek(a)).toBe(false)
    expect(peek(c)).toBe(false)
    s.set(1)
    flush()
    expect(peek(a)).toBe(true)
    expect(peek(c)).toBe(true)
    ua()
    uc()
  })

  it('reflects a source change that happened before the first subscription', () => {
    const s = state(1)
    const isOne = s.is(1)
    s.set(2)
    const unsubscribe = subscribe(isOne)
    expect(peek(isOne)).toBe(false)
    unsubscribe()
  })

  it('does not recompute a dependent state when subscribing to an unchanged .is() result', () => {
    const s = state(1)
    const isOne = s.is(1)
    let runs = 0
    const dependent = compute(() => {
      runs++
      return peek(isOne)
    })
    const unsubscribe = subscribe(dependent)
    expect(peek(dependent)).toBe(true)
    expect(runs).toBe(1)
    s.set(2)
    flush()
    expect(peek(dependent)).toBe(false)
    expect(runs).toBe(2)
    unsubscribe()
  })

  it('reflects a comparand change that happened before the first subscription', () => {
    const s = state({ reference: 1, compared: 2 })
    const d = s.reference.is(s.compared)
    s.compared.set(1)
    const unsubscribe = subscribe(d)
    expect(peek(d)).toBe(true)
    unsubscribe()
  })

  it('reflects such a comparand change when another result shares the old compared value', () => {
    const s = state({ reference: 1, compared: 2 })
    const fixed = s.reference.is(2)
    const d = s.reference.is(s.compared)
    s.compared.set(1)
    const unsubscribeD = subscribe(d)
    const unsubscribeFixed = subscribe(fixed)
    expect(peek(d)).toBe(true)
    expect(peek(fixed)).toBe(false)
    s.reference.set(2)
    flush()
    expect(peek(d)).toBe(false)
    expect(peek(fixed)).toBe(true)
    unsubscribeD()
    unsubscribeFixed()
  })

  it('reflects a comparand change made while unsubscribed, when refreshed before subscribing again', () => {
    const s = state({ reference: 1, compared: 2 })
    const d = s.reference.is(s.compared)
    subscribe(d)()
    s.compared.set(1)
    flush(d)
    expect(peek(d)).toBe(true)
    const unsubscribe = subscribe(d)
    s.compared.set(3)
    flush()
    expect(peek(d)).toBe(false)
    unsubscribe()
  })

  it('should consider NaN to be NaN', () => {
    const s = state({ a: NaN })
    const is = s.a.is(NaN)
    expect(peek(is)).toBe(true)
  })
})
